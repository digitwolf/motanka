# shellcheck shell=bash
# shellcheck disable=SC2034 # variables are used by the tests that load this file
# Shared setup of the Compat_Layer unit tests (wrappers, shims, Helper,
# outcomes, overrides). Everything lives under BATS_TEST_TMPDIR: a fake root
# (MOTANKA_ROOT) with os-release, the lock folder and the System_Ledger, a
# home folder, a Package_Map for resolute, and stubs on PATH for every
# system command the Compat_Layer runs. No test runs the real apt-get, dpkg,
# pkexec, sudo, flatpak, curl or notify-send: the stubs come first on PATH,
# MOTANKA_REAL_SUDO points at a stand-in, and the tests refuse to run as root
# (the Helper ignores its test hooks as root).

# compat_setup: call from setup().
compat_setup() {
  if ((EUID == 0)); then
    skip "the Compat_Layer tests must not run as root"
  fi
  REPO=$(cd "$BATS_TEST_DIRNAME/../.." && pwd -P)
  SRC=$REPO/src
  FIXTURES=$REPO/test/unit/fixtures/compat
  T=$BATS_TEST_TMPDIR
  export MOTANKA_ROOT=$T/root
  mkdir -p "$MOTANKA_ROOT/etc" "$MOTANKA_ROOT/run/lock" "$MOTANKA_ROOT/var/lib"
  printf 'NAME="Ubuntu"\nVERSION_ID="26.04"\nVERSION_CODENAME=resolute\nID=ubuntu\n' \
    >"$MOTANKA_ROOT/etc/os-release"
  export HOME=$T/home
  mkdir -p "$HOME"
  unset MK_HOME XDG_DATA_HOME XDG_CONFIG_HOME XDG_STATE_HOME XDG_CACHE_HOME
  export TMPDIR=$T/tmp
  mkdir -p "$TMPDIR"
  export LOGS=$T/logs
  mkdir -p "$LOGS"
  export FAKE_DPKG=$T/dpkg.tsv
  : >"$FAKE_DPKG"
  export MOTANKA_PACKAGE_MAP=$T/package-map.tsv
  write_map resolute
  STUBS=$T/stubs
  mkdir -p "$STUBS"
  cp -- "$FIXTURES"/stubs/* "$STUBS"/
  chmod +x "$STUBS"/*
  export FLATPAK_STUB=$FIXTURES/stubs/flatpak
  export MOTANKA_REAL_SUDO=$STUBS/real-sudo
  export MOTANKA_PRIVILEGED_TSV=$REPO/compat/privileged.tsv
  unset MOTANKA_HELPER MOTANKA_HELPER_TEST MOTANKA_UPSTREAM_CMD MOTANKA_OMARCHY_PATH
  unset PKEXEC_UID SUDO_UID SUDO_USER FAKE_SIM FAKE_APT_RC FAKE_APT_REAL_RC FAKE_PKEXEC_RC FAKE_HELPER_RC FAKE_CURL_RC
  unset OMARCHY_PATH WAYLAND_DISPLAY DISPLAY
  export FAKE_VIRT=kvm
  export PATH="$STUBS:$PATH"
  LEDGER=$MOTANKA_ROOT/var/lib/motanka/ledger
}

# write_map <release>: the Package_Map fixture, compiled for <release>. The
# two binary outcomes point at $T/download-ns and $T/download-opt.
write_map() {
  local sha_ns sha_opt
  printf 'namespaced binary\n' >"$T/download-ns"
  printf 'opt binary\n' >"$T/download-opt"
  sha_ns=$(sha256sum <"$T/download-ns")
  sha_opt=$(sha256sum <"$T/download-opt")
  {
    printf '# package-map.tsv for %s, generated by tools/pkgmap from packages.yaml; do not edit\n' "$1"
    printf 'chromium\tflatpak\torg.chromium.Chromium\tUbuntu ships Chromium only as a snap\n'
    printf 'fcitx5-gtk\tapt\tfcitx5-frontend-gtk3,fcitx5-frontend-gtk4\t-\n'
    printf 'fd\tapt\tfd-find\tUbuntu installs the command as fdfind\n'
    printf 'gvfs-mtp\tapt\tgvfs-backends\t-\n'
    printf 'gvfs-smb\tapt\tgvfs-backends\t-\n'
    printf 'hyprsunset\tmotanka\tmotanka-stack-tools\tStack build at the version Upstream expects\n'
    printf 'limine\tskip\t-\tbootloader is out of scope\n'
    printf 'nsbin\tbinary\thttps://example.invalid/nsbin\t%s\t~/.local/share/omarchy/bin/nsbin\n' "${sha_ns:0:64}"
    printf 'optbin\tbinary\thttps://example.invalid/optbin\t%s\t/opt/motanka/apps/optbin\n' "${sha_opt:0:64}"
  } >"$MOTANKA_PACKAGE_MAP"
}

# installed <name> [version]: adds a package to the fake dpkg database.
installed() {
  printf '%s\t%s\n' "$1" "${2:-1.0-1}" >>"$FAKE_DPKG"
}

# ledger_line <verb> <fields...>: appends a valid System_Ledger line.
ledger_line() {
  mkdir -p "${LEDGER%/*}"
  local IFS=$'\t'
  printf '2026-11-13T09:00:00Z\t20261113T090000Z-abcdef\t%s\n' "$*" >>"$LEDGER"
}

# use_helper_stub: shims and overrides run the Helper stub.
use_helper_stub() {
  export MOTANKA_HELPER=$STUBS/helper-stub
}

# fake_upstream: a small Upstream tree in $T/omarchy; prints its path.
fake_upstream() {
  local up=$T/omarchy
  mkdir -p "$up/bin" "$up/install"
  printf '# base\nfd\nfcitx5-gtk # input\n\nlimine\nfd\n' >"$up/install/omarchy-base.packages"
  printf '%s\n' "$up"
}

# write_script <path> <body>: an executable bash script.
write_script() {
  mkdir -p "${1%/*}"
  printf '#!/bin/bash\n%s\n' "$2" >"$1"
  chmod +x "$1"
}
