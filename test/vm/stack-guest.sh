#!/usr/bin/env bash
# Guest half of test/vm/tests/stack.sh. Runs INSIDE a throwaway test VM as
# user tester (passwordless sudo in the VM). Never run it on a real machine:
# it installs and purges packages and configures tty1 autologin.
#
# Usage: bash stack-guest.sh <phase> <release> <hyprland-version> <quickshell-version> <qt-version>
#
# Work folder /tmp/motanka-stack-test (T): debs/ holds the Stack .debs
# (motanka-stack, motanka-qt6 and motanka-stack-shell), debcheck is
# tools/debcheck, logs/ collects output, shot.png and shot-shell.png are
# the screenshots, qs/shell.qml is the Quickshell test config and
# qs/probe.webp a 1x1 WebP image it loads. Every check prints "PASS: ..." or
# "FAIL: ..."; the exit code is 1 if any check failed in the phase.
#
# Phases, in the order the host runs them:
#   prepare  install the test tools (binutils, grim), Ubuntu's own Qt 6
#            (ARCHIVE_QT) and, on resolute, Ubuntu's hyprland, and record
#            the package list and the state of those host packages. The
#            host takes the "before" Fingerprint after this phase.
#   install  apt-get install the local .debs; tools/debcheck; paths;
#            RUNPATH, RPATH and ldd of every ELF under /opt/motanka; which
#            libstdc++ the Stack and its Qt use; the Stack's Qt is
#            <qt-version> and has the WebP plugin; quickshell --version,
#            and every Qt library ldd resolves for it comes from
#            /opt/motanka; Ubuntu's hyprland and Qt packages unchanged.
#   session  start /opt/motanka/bin/start-hyprland on tty1 through getty
#            autologin; Hyprland runs from /opt/motanka, hyprctl lists
#            Virtual-1, grim takes a screenshot, no process has
#            LD_LIBRARY_PATH, the loaded libstdc++ is the expected one.
#            Then Quickshell runs qs/shell.qml: a magenta PanelWindow whose
#            layer namespace motanka-test comes from a function declaring
#            `var native` (Qt 6.10's QML grammar rejects it, and the whole
#            file then fails to load), and a cyan PanelWindow with the
#            namespace motanka-webp that is shown only once qs/probe.webp
#            has loaded. hyprctl layers lists both, a pixel inside the
#            magenta one is magenta, grim takes shot-shell.png, and every
#            Qt library and plugin the running Quickshell maps comes from
#            /opt/motanka, including the WebP plugin; none comes from
#            Ubuntu's Qt, which is installed next to it. The autologin
#            drop-in and ~/.bash_profile are removed afterwards.
#   purge    purge the Stack packages and exactly the packages their install
#            pulled in; Ubuntu's hyprland and Qt packages unchanged;
#            /opt/motanka gone. The host takes the "after" Fingerprint after
#            this phase.
set -euo pipefail
export LC_ALL=C.UTF-8
export DEBIAN_FRONTEND=noninteractive

T=/tmp/motanka-stack-test
L=$T/logs
PREFIX=/opt/motanka
TRIPLET_LIBDIR=/usr/lib/x86_64-linux-gnu
# The release's packages are set in main (set_pkgs).
STACK_PKGS=()
SYSTEM_LIB_DIRS=(/lib /lib64 /usr/lib /usr/lib64 /lib/x86_64-linux-gnu /usr/lib/x86_64-linux-gnu)
DROPIN_DIR=/etc/systemd/system/getty@tty1.service.d
DROPIN=$DROPIN_DIR/autologin.conf
PROFILE=$HOME/.bash_profile
APT=(sudo env DEBIAN_FRONTEND=noninteractive apt-get -q -y -o DPkg::Lock::Timeout=300)
# Ubuntu's own Qt 6 (6.4 on noble, 6.10 on resolute), installed before the
# Stack so the checks see the Stack's Qt next to it: it must stay unchanged
# and Quickshell must never load it.
ARCHIVE_QT=(qml6-module-qtquick qt6-wayland)
WEBP_PLUGIN=$PREFIX/lib/qt6/plugins/imageformats/libqwebp.so
# A 1x1 lossy WebP image (the test image of Google's WebP FAQ).
PROBE_WEBP_B64=UklGRiIAAABXRUJQVlA4IBYAAAAwAQCdASoBAAEADsD+JaQAA3AAAAAA

# Quickshell test: a PanelWindow across the top of Virtual-1 (1280x800).
# The pixel is sampled well below the top edge, where Hyprland draws its
# "autogenerated config" warning bar. The WebP panel sits at the bottom.
QS_NAMESPACE=motanka-test
QS_WEBP_NAMESPACE=motanka-webp
QS_HEIGHT=300
QS_PIXEL="100,200"
# QML load errors in Quickshell's output; the first is what Qt 6.10 prints
# for `var native` ("Type BackgroundIntro unavailable ... Expected token
# `identifier'").
QML_ERRORS='Expected token|is not a type|Type [^ ]+ unavailable'

fails=0
pass() { echo "PASS: $*"; }
fail() {
  echo "FAIL: $*"
  fails=$((fails + 1))
}
show() { sed 's/^/    /' "$@" || true; }

guard() {
  local virt
  virt=$(systemd-detect-virt 2>/dev/null || true)
  if [[ -z $virt || $virt == none ]]; then
    echo "stack-guest.sh: refusing to run outside a VM" >&2
    exit 7
  fi
  if [[ -e /etc/motanka-protected || -e $HOME/.config/motanka-protected ]]; then
    echo "stack-guest.sh: refusing to run on a Protected_Host" >&2
    exit 7
  fi
}

installed_list() {
  # shellcheck disable=SC2016 # dpkg-query fields
  dpkg-query -W -f='${binary:Package}\t${db:Status-Status}\n' |
    awk -F'\t' '$2 == "installed" || $2 == "config-files" || $2 == "half-installed" || $2 == "unpacked" || $2 == "half-configured" { print $1 }' |
    sed 's/:amd64$//' | LC_ALL=C sort -u
}

# host_state: version, status and dpkg --verify of the host packages the
# Stack must leave alone: Ubuntu's hyprland (resolute) and every installed
# archive Qt 6 package (libqt6*, qt6-*, qml6-*), plus the checksum of
# Ubuntu's libQt6Core.
host_state() {
  local -a qt=()
  if [[ $RELEASE == resolute ]]; then
    # shellcheck disable=SC2016 # dpkg-query fields
    dpkg-query -W -f='${Package} ${Version} ${db:Status-Abbrev}\n' hyprland 2>/dev/null || echo "hyprland absent"
    sudo dpkg --verify hyprland 2>&1 || true
    if [[ -e /usr/bin/Hyprland ]]; then
      sha256sum /usr/bin/Hyprland
    fi
  fi
  mapfile -t qt < <(installed_list | grep -E '^(libqt6|qt6-|qml6-)' || true)
  echo "archive Qt packages: ${#qt[@]}"
  if ((${#qt[@]} > 0)); then
    # shellcheck disable=SC2016 # dpkg-query fields
    dpkg-query -W -f='${Package} ${Version} ${db:Status-Abbrev}\n' "${qt[@]}"
    sudo dpkg --verify "${qt[@]}" 2>&1 || true
  fi
  if [[ -e $TRIPLET_LIBDIR/libQt6Core.so.6 ]]; then
    sha256sum "$(readlink -f "$TRIPLET_LIBDIR/libQt6Core.so.6")"
  else
    echo "no $TRIPLET_LIBDIR/libQt6Core.so.6"
  fi
}

check_host_unchanged() {
  local when=$1 what="Ubuntu's Qt packages"
  if [[ $RELEASE == resolute ]]; then
    what="Ubuntu's hyprland and Qt packages"
  fi
  host_state >"$L/host-$when.txt"
  if cmp -s "$T/host-before.txt" "$L/host-$when.txt"; then
    pass "$when: $what are installed and unchanged ($(grep -c . "$L/host-$when.txt") lines of state)"
  else
    fail "$when: $what changed"
    diff "$T/host-before.txt" "$L/host-$when.txt" | show
  fi
}

is_elf() {
  [[ $(head -c 4 "$1" 2>/dev/null | od -An -tx1 | tr -d ' \n') == 7f454c46 ]]
}

# A library in a subfolder of a system folder counts too when a package owns
# it: Ubuntu's own libraries load private helpers from there through their
# own RUNPATH (libproxy loads libproxy/libpxbackend-1.0.so).
in_system_dir() {
  local d=${1%/*} s
  for s in "${SYSTEM_LIB_DIRS[@]}"; do
    [[ $d == "$s" ]] && return 0
    if [[ $d == "$s"/* ]] && dpkg-query -S "$1" >/dev/null 2>&1; then
      return 0
    fi
  done
  return 1
}

# --- phases -----------------------------------------------------------------

phase_prepare() {
  local -a tools=(binutils grim "${ARCHIVE_QT[@]}")
  local qt
  mkdir -p "$L"
  if [[ $RELEASE == resolute ]]; then
    tools+=(hyprland)
  fi
  "${APT[@]}" update >"$L/apt-update.log" 2>&1 || {
    fail "apt-get update failed"
    show "$L/apt-update.log"
    return
  }
  if "${APT[@]}" install --no-install-recommends "${tools[@]}" >"$L/prepare.log" 2>&1; then
    pass "installed the test tools and Ubuntu's packages: ${tools[*]}"
  else
    fail "could not install the test tools and Ubuntu's packages: ${tools[*]}"
    show "$L/prepare.log"
  fi
  host_state >"$T/host-before.txt"
  if [[ -e $TRIPLET_LIBDIR/libQt6Core.so.6 ]]; then
    qt=$(readlink -f "$TRIPLET_LIBDIR/libQt6Core.so.6")
    pass "Ubuntu's Qt is installed next to the Stack's: ${qt##*/}"
  else
    fail "Ubuntu's Qt ($TRIPLET_LIBDIR/libQt6Core.so.6) is not installed"
  fi
  installed_list >"$T/pkgs-before.txt"
  if [[ -e $DROPIN || -e $PROFILE ]]; then
    fail "$DROPIN or $PROFILE exists before the test"
  fi
  if grep -rqs toolchain-r /etc/apt/sources.list /etc/apt/sources.list.d/; then
    fail "the toolchain PPA is configured in the test VM"
  else
    pass "no toolchain PPA in the test VM's apt sources"
  fi
  echo "system libstdc++ provides up to: $(grep -ao 'GLIBCXX_3\.4\.[0-9]*' "$(readlink -f /usr/lib/x86_64-linux-gnu/libstdc++.so.6)" | sort -Vu | tail -n 1)"
  echo "kernel.apparmor_restrict_unprivileged_userns = $(sysctl -n kernel.apparmor_restrict_unprivileged_userns 2>/dev/null || echo absent)"
}

check_paths() {
  local p f bad=0
  for p in "${STACK_PKGS[@]}"; do
    while IFS= read -r f; do
      case $f in
        /. | /opt | /usr | /usr/share | /usr/share/doc | /usr/share/lintian | /usr/share/lintian/overrides) ;;
        "$PREFIX" | "$PREFIX"/*) ;;
        /usr/share/doc/"$p" | /usr/share/doc/"$p"/*) ;;
        /usr/share/lintian/overrides/"$p") ;;
        *)
          fail "$p installs $f outside $PREFIX"
          bad=1
          ;;
      esac
    done < <(dpkg -L "$p")
  done
  if ((bad == 0)); then
    pass "every Stack file is under $PREFIX (plus /usr/share/doc/<pkg> and lintian overrides)"
  fi
}

check_elves() {
  local f dyn runpath comp needs_stack line lib target n=0 bad=0
  local -a parts
  while IFS= read -r -d '' f; do
    is_elf "$f" || continue
    n=$((n + 1))
    dyn=$(readelf -d "$f" 2>/dev/null || true)
    if grep -q '(RPATH)' <<<"$dyn"; then
      fail "$f has an RPATH: $(grep '(RPATH)' <<<"$dyn")"
      bad=1
    fi
    runpath=$(sed -n 's/.*(RUNPATH).*\[\(.*\)\]$/\1/p' <<<"$dyn")
    if [[ -n $runpath ]]; then
      IFS=: read -r -a parts <<<"$runpath"
      for comp in "${parts[@]}"; do
        if [[ $comp != "$PREFIX/lib" ]]; then
          fail "$f has RUNPATH '$runpath' (only $PREFIX/lib allowed)"
          bad=1
          break
        fi
      done
    fi
    grep -q '(NEEDED)' <<<"$dyn" || continue
    ldd "$f" >"$L/ldd.tmp" 2>&1 || true
    needs_stack=false
    while IFS= read -r line; do
      if [[ $line == *"not found"* ]]; then
        fail "$f: unresolved library: ${line//[[:space:]]/ }"
        bad=1
        continue
      fi
      [[ $line == *" => "* ]] || continue
      lib=${line#*=> }
      target=${lib%% (*}
      [[ $target == /* ]] || continue
      if [[ $target == "$PREFIX/lib/"* ]]; then
        needs_stack=true
      elif ! in_system_dir "$target"; then
        fail "$f resolves ${line%% =>*} from $target, outside $PREFIX/lib and the system library folders"
        bad=1
      fi
    done <"$L/ldd.tmp"
    if $needs_stack && [[ -z $runpath ]]; then
      case ${f##*/} in
        libstdc++.so.6 | libgcc_s.so.1) ;;
        *)
          fail "$f loads Stack libraries but has no RUNPATH"
          bad=1
          ;;
      esac
    fi
  done < <(sudo find "$PREFIX" -type f -print0)
  rm -f "$L/ldd.tmp"
  if ((n == 0)); then
    fail "no ELF file under $PREFIX"
  elif ((bad == 0)); then
    pass "$n ELF files: no RPATH, RUNPATH only $PREFIX/lib, every library resolves from $PREFIX/lib or the system"
  fi
}

# check_cxx_runtime_of <label> <elf>: noble loads the bundled libstdc++,
# resolute the system one.
check_cxx_runtime_of() {
  local label=$1 elf=$2 got gcc out
  out=$(ldd "$elf" 2>&1 || true)
  got=$(awk '$1 == "libstdc++.so.6" { print $3 }' <<<"$out")
  gcc=$(awk '$1 == "libgcc_s.so.1" { print $3 }' <<<"$out")
  if [[ $RELEASE == noble ]]; then
    if [[ $got == "$PREFIX/lib/libstdc++.so.6" ]]; then
      pass "noble: $label uses the bundled libstdc++ ($got)"
    else
      fail "noble: $label uses libstdc++ from '${got:-nowhere}', expected $PREFIX/lib/libstdc++.so.6"
    fi
    if [[ -z $gcc || $gcc == "$PREFIX/lib/libgcc_s.so.1" ]]; then
      pass "noble: $label's libgcc_s is the bundled one (${gcc:-not needed directly})"
    else
      fail "noble: $label uses libgcc_s from $gcc"
    fi
  else
    if [[ $got == "$TRIPLET_LIBDIR/libstdc++.so.6" ]]; then
      pass "resolute: $label uses the system libstdc++ ($got)"
    else
      fail "resolute: $label uses libstdc++ from '${got:-nowhere}', expected the system one"
    fi
  fi
}

check_cxx_runtime() {
  check_cxx_runtime_of Hyprland "$PREFIX/bin/Hyprland"
  check_cxx_runtime_of "the Stack's libQt6Core" "$PREFIX/lib/libQt6Core.so.6"
  if [[ $RELEASE == resolute ]]; then
    if compgen -G "$PREFIX/lib/libstdc++*" >/dev/null || compgen -G "$PREFIX/lib/libgcc_s*" >/dev/null; then
      fail "resolute: a C++ runtime is bundled in $PREFIX/lib"
    else
      pass "resolute: no C++ runtime bundled"
    fi
  fi
}

# qt_path <path>: the path is a Qt library, plugin or QML module file.
# Quickshell's own QML modules (lib/qt6/qml/Quickshell*) are not Qt's.
qt_path() {
  [[ $1 == "$PREFIX/lib/qt6/qml/Quickshell"* ]] && return 1
  [[ $1 =~ /libQt6[^/]*\.so || $1 =~ /qt6/(plugins|qml)/ ]]
}

# check_qt_origin <label> <file with one path per line>: every Qt path is
# under /opt/motanka on both releases; none is Ubuntu's Qt
# (/usr/lib/x86_64-linux-gnu/libQt6*, .../qt6/plugins, .../qt6/qml).
check_qt_origin() {
  local label=$1 list=$2 p n=0
  local -a bad=()
  while IFS= read -r p; do
    qt_path "$p" || continue
    n=$((n + 1))
    if [[ $p != "$PREFIX"/* ]]; then
      bad+=("$p")
    fi
  done <"$list"
  if ((n == 0)); then
    fail "$label: no Qt library at all"
  elif ((${#bad[@]} > 0)); then
    fail "$label: ${#bad[@]} of $n Qt files are not from $PREFIX:"
    printf '%s\n' "${bad[@]}" | show
  else
    pass "$label: all $n Qt files are from $PREFIX, none from Ubuntu's Qt"
  fi
}

# check_stack_qt: the Stack's Qt is QT_VERSION and has the WebP plugin.
check_stack_qt() {
  local core owner
  core=$(readlink -f "$PREFIX/lib/libQt6Core.so.6" 2>/dev/null || true)
  if [[ $core == "$PREFIX/lib/libQt6Core.so.$QT_VERSION" ]]; then
    pass "the Stack's Qt is $QT_VERSION ($core)"
  else
    fail "the Stack's libQt6Core.so.6 is '${core:-missing}', expected $PREFIX/lib/libQt6Core.so.$QT_VERSION"
  fi
  owner=$(dpkg-query -S "$WEBP_PLUGIN" 2>/dev/null || true)
  if [[ -f $WEBP_PLUGIN && $owner == motanka-qt6:* ]]; then
    pass "motanka-qt6 ships the WebP image plugin $WEBP_PLUGIN"
  else
    fail "$WEBP_PLUGIN is missing or not owned by motanka-qt6"
  fi
}

# qs_env: the environment Quickshell runs with outside the session (state
# and caches in the work folder, never in $HOME).
qs_env() {
  printf '%s\n' HOME="$HOME" USER="$(id -un)" LANG=C.UTF-8 PATH="$PREFIX/bin:/usr/bin:/bin" \
    XDG_CONFIG_HOME="$T/xdg/config" XDG_DATA_HOME="$T/xdg/data" \
    XDG_STATE_HOME="$T/xdg/state" XDG_CACHE_HOME="$T/xdg/cache" \
    DCONF_PROFILE="$T/dconf-profile"
}

check_shell_install() {
  local qs=$PREFIX/bin/quickshell v std target line
  local -a envs
  if [[ ! -x $qs ]]; then
    fail "$qs is missing"
    return
  fi
  mkdir -p "$T/xdg/config" "$T/xdg/data" "$T/xdg/state" "$T/xdg/cache"
  : >"$T/dconf-profile"
  mapfile -t envs < <(qs_env)
  v=$(env -i "${envs[@]}" "$qs" --version 2>&1 | head -n 3 || true)
  if grep -qF "$QS_VERSION" <<<"$v"; then
    pass "quickshell --version reports $QS_VERSION: $(head -n 1 <<<"$v")"
  else
    fail "quickshell --version does not report $QS_VERSION:"
    printf '%s\n' "$v" | show
  fi
  ldd "$qs" >"$L/ldd-quickshell.txt" 2>&1 || true
  while IFS= read -r line; do
    [[ $line == *" => "* ]] || continue
    target=${line#*=> }
    target=${target%% (*}
    if [[ $target == /* ]]; then
      printf '%s\n' "$target"
    fi
  done <"$L/ldd-quickshell.txt" >"$L/ldd-quickshell.paths"
  check_qt_origin "ldd quickshell" "$L/ldd-quickshell.paths"
  if grep -q 'libcpptrace\.so' "$L/ldd-quickshell.txt"; then
    if grep -q "libcpptrace\.so.* => $PREFIX/lib/" "$L/ldd-quickshell.txt"; then
      pass "quickshell uses libcpptrace from $PREFIX/lib"
    else
      fail "quickshell resolves libcpptrace outside $PREFIX/lib: $(grep libcpptrace "$L/ldd-quickshell.txt")"
    fi
  fi
  std=$(awk '$1 == "libstdc++.so.6" { print $3 }' "$L/ldd-quickshell.txt")
  if [[ $RELEASE == noble ]]; then
    if [[ $std == "$PREFIX/lib/libstdc++.so.6" ]]; then
      pass "noble: quickshell uses the bundled libstdc++"
    else
      fail "noble: quickshell uses libstdc++ from '${std:-nowhere}'"
    fi
  else
    if [[ $std == "$TRIPLET_LIBDIR/libstdc++.so.6" ]]; then
      pass "resolute: quickshell uses the system libstdc++"
    else
      fail "resolute: quickshell uses libstdc++ from '${std:-nowhere}', expected the system one"
    fi
  fi
}

phase_install() {
  local p rc=0 v
  mkdir -p "$L"
  "${APT[@]}" install "$T"/debs/*.deb >"$L/install.log" 2>&1 || rc=$?
  if ((rc == 0)); then
    pass "apt-get installed the local Stack .debs: $(cd "$T/debs" && echo ./*.deb)"
  else
    fail "apt-get install of the Stack .debs failed (exit $rc)"
    show "$L/install.log"
    return
  fi
  for p in "${STACK_PKGS[@]}"; do
    # shellcheck disable=SC2016 # dpkg-query field
    if [[ $(dpkg-query -W -f='${db:Status-Abbrev}' "$p" 2>/dev/null) == "ii " ]]; then
      pass "$p is installed"
    else
      fail "$p is not installed"
    fi
  done
  rc=0
  python3 "$T/debcheck" "$T"/debs/*.deb >"$L/debcheck.log" 2>&1 || rc=$?
  if ((rc == 0)); then
    pass "tools/debcheck passes on every Stack .deb"
  else
    fail "tools/debcheck found problems (exit $rc)"
    show "$L/debcheck.log"
  fi
  check_paths
  check_elves
  check_cxx_runtime
  check_stack_qt
  check_shell_install
  v=$("$PREFIX/bin/Hyprland" --version 2>&1 | head -n 3 || true)
  if grep -qF "$HYPR_VERSION" <<<"$v"; then
    pass "Hyprland --version reports $HYPR_VERSION"
  else
    fail "Hyprland --version does not report $HYPR_VERSION:"
    printf '%s\n' "$v" | show
  fi
  if compgen -G "/etc/ld.so.conf.d/*motanka*" >/dev/null || grep -qs LD_LIBRARY_PATH /etc/environment; then
    fail "an ld.so.conf.d entry or LD_LIBRARY_PATH in /etc/environment appeared"
  else
    pass "no ld.so.conf.d entry and no LD_LIBRARY_PATH in /etc/environment"
  fi
  check_host_unchanged after-install
}

session_teardown() {
  local id
  pkill -KILL -u "$(id -u)" -f "^$PREFIX/bin/quickshell" 2>/dev/null || true
  sudo rm -f -- "$DROPIN"
  sudo rmdir -- "$DROPIN_DIR" 2>/dev/null || true
  rm -f -- "$PROFILE"
  sudo systemctl daemon-reload
  for id in $(loginctl list-sessions --no-legend 2>/dev/null | awk '$0 ~ /tty1/ { print $1 }'); do
    sudo loginctl terminate-session "$id" 2>/dev/null || true
  done
  sudo systemctl restart getty@tty1 2>/dev/null || true
  for _ in $(seq 30); do
    pgrep -u "$(id -u)" -x Hyprland >/dev/null || break
    sleep 1
  done
  if pgrep -u "$(id -u)" -x Hyprland >/dev/null; then
    fail "Hyprland still runs after the session was terminated"
    pkill -KILL -u "$(id -u)" -x Hyprland || true
  fi
}

phase_session() {
  session_run || true
  session_teardown
}

session_run() {
  local pid exe rt sig wl found leaks lib want
  mkdir -p "$L" "$T/xdg/config" "$T/xdg/data" "$T/xdg/state" "$T/xdg/cache"
  sudo mkdir -p "$DROPIN_DIR"
  # shellcheck disable=SC2016 # $TERM is for systemd, not this shell
  printf '[Service]\nExecStart=\nExecStart=-/sbin/agetty --autologin %s --noclear %%I $TERM\n' "$(id -un)" |
    sudo tee "$DROPIN" >/dev/null
  # Hyprland's own config, data and cache go to the work folder, not $HOME.
  # dconf writes go through dconf-service, which D-Bus starts with the user's
  # default environment, so XDG_CONFIG_HOME does not redirect them; an empty
  # dconf profile (no user database) keeps the session from creating
  # ~/.config/dconf/user. The Motanka session uses its own profile instead.
  : >"$T/dconf-profile"
  cat >"$PROFILE" <<EOF
if [ "\$(tty)" = /dev/tty1 ] && [ -x $PREFIX/bin/start-hyprland ]; then
  export XDG_CONFIG_HOME=$T/xdg/config XDG_DATA_HOME=$T/xdg/data XDG_STATE_HOME=$T/xdg/state XDG_CACHE_HOME=$T/xdg/cache
  export PATH=$PREFIX/bin:\$PATH DCONF_PROFILE=$T/dconf-profile
  exec $PREFIX/bin/start-hyprland --path $PREFIX/bin/Hyprland >$T/logs/start-hyprland.log 2>&1
fi
EOF
  sudo systemctl daemon-reload
  sudo systemctl restart getty@tty1

  pid=""
  for _ in $(seq 90); do
    pid=$(pgrep -u "$(id -u)" -x Hyprland | head -n 1 || true)
    [[ -n $pid ]] && break
    sleep 1
  done
  if [[ -z $pid ]]; then
    fail "Hyprland did not start on tty1 within 90 s"
    show "$T/logs/start-hyprland.log"
    return
  fi
  exe=$(readlink "/proc/$pid/exe" || true)
  if [[ $exe == "$PREFIX/bin/Hyprland" ]]; then
    pass "Hyprland runs from $exe (pid $pid) under start-hyprland"
  else
    fail "the running Hyprland is $exe, not $PREFIX/bin/Hyprland"
  fi

  rt=/run/user/$(id -u)
  sig=""
  found=false
  for _ in $(seq 60); do
    sig=$(find "$rt/hypr" -mindepth 1 -maxdepth 1 -type d -printf '%T@ %f\n' 2>/dev/null | sort -n | tail -n 1 | cut -d' ' -f2)
    if [[ -n $sig ]] && HYPRLAND_INSTANCE_SIGNATURE=$sig XDG_RUNTIME_DIR=$rt \
      "$PREFIX/bin/hyprctl" monitors >"$L/hyprctl-monitors.txt" 2>&1 &&
      grep -q 'Virtual-1' "$L/hyprctl-monitors.txt"; then
      found=true
      break
    fi
    sleep 1
  done
  if $found; then
    pass "hyprctl monitors lists Virtual-1: $(grep -m1 'Virtual-1' "$L/hyprctl-monitors.txt")"
  else
    fail "hyprctl monitors does not list Virtual-1"
    show "$L/hyprctl-monitors.txt"
  fi
  if [[ -n $sig && -f $rt/hypr/$sig/hyprland.log ]]; then
    cp -f "$rt/hypr/$sig/hyprland.log" "$L/hyprland.log"
    grep -E 'Renderer:|drm: Starting backend' "$L/hyprland.log" | head -n 3 || true
  fi

  wl=$(find "$rt" -maxdepth 1 -type s -name 'wayland-[0-9]*' -printf '%f\n' 2>/dev/null | sort | head -n 1)
  rm -f "$T/shot.png"
  if [[ -n $wl ]] && XDG_RUNTIME_DIR=$rt WAYLAND_DISPLAY=$wl grim "$T/shot.png" >"$L/grim.log" 2>&1 &&
    [[ $(head -c 8 "$T/shot.png" | od -An -tx1 | tr -d ' \n') == 89504e470d0a1a0a ]]; then
    pass "grim captured a screenshot from $wl ($(stat -c %s "$T/shot.png") bytes)"
  else
    fail "grim could not capture a screenshot (socket '${wl:-none}')"
    show "$L/grim.log"
  fi

  # shellcheck disable=SC2016 # the script runs in the root shell
  leaks=$(sudo bash -c 'for f in /proc/[0-9]*/environ; do
      if tr "\0" "\n" <"$f" 2>/dev/null | grep -q "^LD_LIBRARY_PATH="; then
        p=${f#/proc/}; p=${p%/environ}
        printf "%s %s\n" "$p" "$(tr "\0" " " <"/proc/$p/cmdline" 2>/dev/null | cut -c1-120)"
      fi
    done')
  if [[ -z $leaks ]]; then
    pass "no process has LD_LIBRARY_PATH in its environment"
  else
    fail "processes with LD_LIBRARY_PATH:"
    printf '%s\n' "$leaks" | show
  fi

  lib=$(sudo grep -o '/[^ ]*libstdc++\.so[^ ]*' "/proc/$pid/maps" | sort -u | head -n 1 || true)
  if [[ $RELEASE == noble ]]; then
    want=$PREFIX/lib/libstdc++.so.6
  else
    want=$TRIPLET_LIBDIR/libstdc++.so.6
  fi
  if [[ $(readlink -f "${lib:-/nonexistent}" 2>/dev/null) == "$(readlink -f "$want")" ]]; then
    pass "the running Hyprland has $lib mapped"
  else
    fail "the running Hyprland maps libstdc++ '${lib:-none}', expected $want"
  fi
  if [[ -n $wl && -n $sig ]]; then
    shell_run "$rt" "$wl" "$sig"
  else
    fail "Quickshell test skipped: no Wayland socket or Hyprland instance"
  fi
  check_host_unchanged after-session
}

write_shell_qml() {
  mkdir -p "$T/qs"
  base64 -d <<<"$PROBE_WEBP_B64" >"$T/qs/probe.webp"
  cat >"$T/qs/shell.qml" <<EOF
// Quickshell test config of test/vm/stack-guest.sh: one magenta panel, and
// a cyan one that is shown once a WebP image has loaded.
import Quickshell
import Quickshell.Wayland
import QtQuick

ShellRoot {
  id: root

  // Regression check for the Qt 6.10 QML grammar, which rejects \`native\`
  // as a JavaScript identifier (Upstream's shell declares \`var native\`).
  // A parse error stops the whole file, so no panel would appear.
  function nativeNamespace() {
    var native = "$QS_NAMESPACE"
    return native
  }

  PanelWindow {
    WlrLayershell.namespace: root.nativeNamespace()
    anchors {
      top: true
      left: true
      right: true
    }
    implicitHeight: $QS_HEIGHT
    color: "#ff00ff"

    Image {
      id: webpProbe
      source: "file://$T/qs/probe.webp"
      width: 1
      height: 1
    }
  }

  PanelWindow {
    visible: webpProbe.status === Image.Ready
    WlrLayershell.namespace: "$QS_WEBP_NAMESPACE"
    anchors {
      bottom: true
      left: true
      right: true
    }
    implicitHeight: 40
    color: "#00ffff"
  }
}
EOF
}

# pixel_rgb <runtime-dir> <wayland-socket>: prints "R G B" of QS_PIXEL.
pixel_rgb() {
  XDG_RUNTIME_DIR=$1 WAYLAND_DISPLAY=$2 grim -g "$QS_PIXEL 1x1" -t ppm - 2>>"$L/grim-shell.log" |
    tail -c 3 | od -An -tu1 | xargs
}

# wait_layer <runtime-dir> <signature> <namespace> <pid> <seconds>: returns 0
# once hyprctl layers lists the namespace, 1 on timeout or when the process
# exits.
wait_layer() {
  local rt=$1 sig=$2 ns=$3 pid=$4 secs=$5
  for _ in $(seq "$secs"); do
    if ! kill -0 "$pid" 2>/dev/null; then
      return 1
    fi
    if HYPRLAND_INSTANCE_SIGNATURE=$sig XDG_RUNTIME_DIR=$rt "$PREFIX/bin/hyprctl" layers \
      >"$L/hyprctl-layers.txt" 2>&1 && grep -qF "$ns" "$L/hyprctl-layers.txt"; then
      return 0
    fi
    sleep 1
  done
  return 1
}

# shell_run <runtime-dir> <wayland-socket> <hyprland-signature>
shell_run() {
  local rt=$1 wl=$2 sig=$3 qs=$PREFIX/bin/quickshell pid exe found=false rgb="" r g b ok=false
  local -a envs
  write_shell_qml
  mapfile -t envs < <(qs_env)
  envs+=(XDG_RUNTIME_DIR="$rt" WAYLAND_DISPLAY="$wl" HYPRLAND_INSTANCE_SIGNATURE="$sig"
    XDG_CURRENT_DESKTOP=Hyprland XDG_SESSION_TYPE=wayland QT_QPA_PLATFORM=wayland)
  if [[ -S $rt/bus ]]; then
    envs+=(DBUS_SESSION_BUS_ADDRESS="unix:path=$rt/bus")
  fi
  : >"$L/quickshell.log"
  # A background setsid in a non-interactive shell does not fork, and env
  # execs, so $! is Quickshell's pid.
  setsid env -i "${envs[@]}" "$qs" -p "$T/qs/shell.qml" </dev/null >"$L/quickshell.log" 2>&1 &
  pid=$!

  if wait_layer "$rt" "$sig" "$QS_NAMESPACE" "$pid" 60; then
    found=true
  fi
  if ! kill -0 "$pid" 2>/dev/null; then
    fail "Quickshell exited within 60 s"
    show "$L/quickshell.log"
    return
  fi
  exe=$(readlink "/proc/$pid/exe" || true)
  if [[ $exe == "$qs" ]]; then
    pass "Quickshell runs from $exe (pid $pid)"
  else
    fail "the started process runs '$exe', not $qs"
  fi
  if $found; then
    pass "hyprctl layers lists the Quickshell panel, whose namespace comes from a function declaring 'var native': $(grep -m1 -F "$QS_NAMESPACE" "$L/hyprctl-layers.txt" | sed 's/^[[:space:]]*//')"
  else
    fail "hyprctl layers does not list the namespace $QS_NAMESPACE within 60 s"
    show "$L/hyprctl-layers.txt"
    show "$L/quickshell.log"
  fi
  if grep -qE "$QML_ERRORS" "$L/quickshell.log"; then
    fail "Quickshell reported a QML load error:"
    grep -E "$QML_ERRORS" "$L/quickshell.log" | head -n 5 | show
  else
    pass "Quickshell's log has no QML parse or type error"
  fi
  if wait_layer "$rt" "$sig" "$QS_WEBP_NAMESPACE" "$pid" 20; then
    pass "the WebP probe image loaded: hyprctl layers lists $QS_WEBP_NAMESPACE"
  else
    fail "hyprctl layers does not list $QS_WEBP_NAMESPACE within 20 s (the WebP image did not load)"
    show "$L/quickshell.log"
  fi

  # The layer fades in; wait until the sampled pixel is magenta.
  for _ in $(seq 30); do
    rgb=$(pixel_rgb "$rt" "$wl") || rgb=""
    read -r r g b <<<"$rgb" || true
    if [[ ${r:-} =~ ^[0-9]+$ && ${g:-} =~ ^[0-9]+$ && ${b:-} =~ ^[0-9]+$ ]] &&
      ((r >= 215 && g <= 40 && b >= 215)); then
      ok=true
      break
    fi
    sleep 1
  done
  if $ok; then
    pass "the pixel at $QS_PIXEL is the panel's magenta (RGB $rgb)"
  else
    fail "the pixel at $QS_PIXEL is RGB '${rgb:-unreadable}', not the panel's magenta"
    show "$L/grim-shell.log"
  fi
  rm -f "$T/shot-shell.png"
  if XDG_RUNTIME_DIR=$rt WAYLAND_DISPLAY=$wl grim "$T/shot-shell.png" >>"$L/grim-shell.log" 2>&1 &&
    [[ $(head -c 8 "$T/shot-shell.png" | od -An -tx1 | tr -d ' \n') == 89504e470d0a1a0a ]]; then
    pass "grim captured the Quickshell screenshot ($(stat -c %s "$T/shot-shell.png") bytes)"
  else
    fail "grim could not capture the Quickshell screenshot"
    show "$L/grim-shell.log"
  fi

  sudo cat "/proc/$pid/maps" 2>/dev/null | awk '$6 ~ /^\// { print $6 }' | LC_ALL=C sort -u >"$L/quickshell-maps.txt" || true
  check_qt_origin "running Quickshell" "$L/quickshell-maps.txt"
  if grep -q "^$TRIPLET_LIBDIR/libQt6" "$L/quickshell-maps.txt"; then
    fail "the running Quickshell maps Ubuntu's Qt libraries:"
    grep "^$TRIPLET_LIBDIR/libQt6" "$L/quickshell-maps.txt" | show
  else
    pass "the running Quickshell maps no $TRIPLET_LIBDIR/libQt6* library"
  fi
  if grep -qE '/qt6/plugins/platforms/libqwayland' "$L/quickshell-maps.txt"; then
    pass "the running Quickshell loaded the Qt Wayland platform plugin: $(grep -m1 -E '/qt6/plugins/platforms/libqwayland' "$L/quickshell-maps.txt")"
  else
    fail "the running Quickshell has no Qt Wayland platform plugin mapped"
  fi
  if grep -qxF "$WEBP_PLUGIN" "$L/quickshell-maps.txt"; then
    pass "the running Quickshell loaded the Stack's WebP plugin $WEBP_PLUGIN"
  else
    fail "the running Quickshell does not map $WEBP_PLUGIN"
  fi
  if [[ $RELEASE == noble ]]; then
    if grep -qxF "$PREFIX/lib/libstdc++.so.6" "$L/quickshell-maps.txt"; then
      pass "noble: the running Quickshell maps the bundled libstdc++"
    else
      fail "noble: the running Quickshell does not map $PREFIX/lib/libstdc++.so.6"
    fi
  fi
  if tr '\0' '\n' <"/proc/$pid/environ" 2>/dev/null | grep -q '^LD_LIBRARY_PATH='; then
    fail "Quickshell has LD_LIBRARY_PATH in its environment"
  else
    pass "Quickshell has no LD_LIBRARY_PATH"
  fi

  kill -TERM "$pid" 2>/dev/null || true
  for _ in $(seq 15); do
    kill -0 "$pid" 2>/dev/null || break
    sleep 1
  done
  if kill -0 "$pid" 2>/dev/null; then
    fail "Quickshell still runs 15 s after SIGTERM"
    kill -KILL "$pid" 2>/dev/null || true
  else
    pass "Quickshell stopped on SIGTERM"
  fi
}

phase_purge() {
  local rc=0 p
  local -a present=() extra=()
  mkdir -p "$L"
  for p in "${STACK_PKGS[@]}"; do
    if dpkg-query -W "$p" >/dev/null 2>&1; then
      present+=("$p")
    fi
  done
  if ((${#present[@]} > 0)); then
    "${APT[@]}" purge "${present[@]}" >"$L/purge.log" 2>&1 || rc=$?
  fi
  if ((rc == 0)); then
    pass "purged ${present[*]:-nothing}"
  else
    fail "apt-get purge of the Stack failed (exit $rc)"
    show "$L/purge.log"
  fi
  mapfile -t extra < <(installed_list | LC_ALL=C comm -13 "$T/pkgs-before.txt" -)
  if ((${#extra[@]} > 0)); then
    rc=0
    "${APT[@]}" purge "${extra[@]}" >"$L/purge-deps.log" 2>&1 || rc=$?
    if ((rc == 0)); then
      pass "purged the ${#extra[@]} packages the Stack pulled in"
    else
      fail "could not purge the packages the Stack pulled in (exit $rc)"
      show "$L/purge-deps.log"
    fi
  fi
  if [[ -e $PREFIX ]]; then
    fail "$PREFIX still exists after purge:"
    sudo find "$PREFIX" | head -n 20 | show
  else
    pass "$PREFIX is gone"
  fi
  if [[ -n $(installed_list | LC_ALL=C comm -3 "$T/pkgs-before.txt" -) ]]; then
    fail "the package set differs from before the install:"
    installed_list | LC_ALL=C comm -3 "$T/pkgs-before.txt" - | show
  else
    pass "the package set equals the one before the install"
  fi
  check_host_unchanged after-purge
}

# set_pkgs: the Stack packages, as the host stages them (the same on both
# releases).
set_pkgs() {
  STACK_PKGS=(motanka-stack motanka-stack-hyprland motanka-stack-tools motanka-stack-shell motanka-qt6 motanka-stack-libs)
}

main() {
  (($# == 5)) || {
    echo "usage: bash stack-guest.sh <prepare|install|session|purge> <release> <hyprland-version> <quickshell-version> <qt-version>" >&2
    exit 2
  }
  PHASE=$1
  RELEASE=$2
  HYPR_VERSION=$3
  QS_VERSION=$4
  QT_VERSION=$5
  case $RELEASE in
    noble | resolute) ;;
    *)
      echo "unknown release '$RELEASE'" >&2
      exit 2
      ;;
  esac
  if [[ ! $QT_VERSION =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "invalid Qt version '$QT_VERSION'" >&2
    exit 2
  fi
  set_pkgs
  guard
  case $PHASE in
    prepare) phase_prepare ;;
    install) phase_install ;;
    session) phase_session ;;
    purge) phase_purge ;;
    *)
      echo "unknown phase '$PHASE'" >&2
      exit 2
      ;;
  esac
  exit $((fails > 0 ? 1 : 0))
}

main "$@"
